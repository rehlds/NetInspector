#!/usr/bin/env bash
# Writes msvc/NetInspector.vcxitems from the source tree: every recorder source but the
# POSIX platform and the decoder, each with an object file name of its own, and every header. Run it after
# adding, moving or removing a source file.

set -euo pipefail

cd "$(dirname "$0")/.."
output="msvc/NetInspector.vcxitems"

windows_path()
{
	echo "$1" | tr / '\\'
}

{
	cat <<'EOF'
<?xml version="1.0" encoding="utf-8"?>
<!-- The recorder for msbuild projects that compile it in:
     <Import Project="...\NetInspector.vcxitems" Label="Shared" />
     The sources build with the importing project's toolset and flags; include\ joins its include path.
     Object files carry a netinspector_ prefix, so they never collide with the project's own.
     Generated by scripts/generate_vcxitems.sh. -->
<Project xmlns="http://schemas.microsoft.com/developer/msbuild/2003">
  <PropertyGroup Label="Globals">
    <MSBuildAllProjects Condition="'$(MSBuildVersion)' == '' Or '$(MSBuildVersion)' &lt; '16.0'">$(MSBuildAllProjects);$(MSBuildThisFileFullPath)</MSBuildAllProjects>
    <HasSharedItems>true</HasSharedItems>
    <ItemsProjectGuid>{30261619-5098-4D58-8094-55DB0D045FD4}</ItemsProjectGuid>
    <ItemsProjectName>NetInspector</ItemsProjectName>
  </PropertyGroup>
  <ItemGroup>
    <ProjectCapability Include="SourceItemsFromImports" />
  </ItemGroup>
  <ItemDefinitionGroup>
    <ClCompile>
      <AdditionalIncludeDirectories>$(MSBuildThisFileDirectory)..\include;%(AdditionalIncludeDirectories)</AdditionalIncludeDirectories>
    </ClCompile>
  </ItemDefinitionGroup>
  <ItemGroup>
EOF

	find src -name '*.cpp' -not -path '*/platform/posix/*' -not -path '*/decoder/*' | sort | while IFS= read -r source; do
		object="$(echo "${source#src/netinspector/}" | sed 's/\.cpp$//' | tr / _)"
		cat <<EOF
    <ClCompile Include="\$(MSBuildThisFileDirectory)..\\$(windows_path "$source")">
      <PrecompiledHeader>NotUsing</PrecompiledHeader>
      <AdditionalIncludeDirectories>\$(MSBuildThisFileDirectory)..\\include;\$(MSBuildThisFileDirectory)..\\src;%(AdditionalIncludeDirectories)</AdditionalIncludeDirectories>
      <ObjectFileName>\$(IntDir)netinspector_$object.obj</ObjectFileName>
    </ClCompile>
EOF
	done

	echo '  </ItemGroup>'
	echo '  <ItemGroup>'

	find include src -name '*.h' -not -path '*/platform/posix/*' -not -path '*/decoder/*' | sort | while IFS= read -r header; do
		echo "    <ClInclude Include=\"\$(MSBuildThisFileDirectory)..\\$(windows_path "$header")\" />"
	done

	echo '  </ItemGroup>'
	echo '</Project>'
} | sed 's/$/\r/' > "$output"

echo "$output"
